def viec_bi_chan(cuoc):
    """Đọc nhật ký cuộc trò chuyện agy -> [{loai: command|write_file|read_file, gia_tri, cong_cu}] của các bước bị từ chối."""
    import sqlite3
    f = os.path.join(_CUOC_DB, f"{cuoc}.db")
    if not cuoc or not os.path.isfile(f):
        return []
    ra = []
    try:
        c = sqlite3.connect(f"file:{f}?mode=ro", uri=True)
        hang = c.execute("select step_type, status, step_payload from steps order by idx").fetchall()
        c.close()
    except sqlite3.Error:
        return []
    for loai_buoc, tt, p in hang:
        if loai_buoc != 132 or tt not in (6, 7):                         # 132 = bước dùng công cụ; 6 / 7 = bị từ chối
            continue
        s = (p or b"").decode("utf-8", "ignore")
        m = re.search(r"([a-z_]{4,30})[^a-z_{]{1,6}(\{\")", s)
        if not m:
            continue
        try:
            tham, _ = json.JSONDecoder().raw_decode(s[m.start(2):])
        except ValueError:
            continue
        cc = m.group(1)
        if "CommandLine" in tham:
            ra.append({"loai": "command", "gia_tri": str(tham["CommandLine"]).strip(), "cong_cu": cc})
            continue
        duong = next((tham[k] for k in ("Path", "TargetFile", "AbsolutePath", "FilePath", "DirectoryPath", "File")
                      if isinstance(tham.get(k), str)), None)
        if duong:
            ghi = any(x in cc for x in ("write", "edit", "replace", "create", "delete", "move"))
            ra.append({"loai": "write_file" if ghi else "read_file", "gia_tri": duong, "cong_cu": cc})
    return ra


def _trong(duong, goc):
    try:
        return os.path.commonpath([os.path.normcase(os.path.abspath(duong)), os.path.normcase(goc)]) == os.path.normcase(goc)
    except ValueError:
        return False


def _nguy_hiem(v):
    """-> lý do (tự từ chối, không hỏi user) | '' (được hỏi)."""
    g = v["gia_tri"]
    if v["loai"] == "command":
        if _LENH_CAM.search(g):
            return "lệnh có thể xoá / dời / ghi tệp, cài đặt, lên mạng hoặc nối nhiều lệnh"
        if re.search(r"\b(npx|pnpx|yarn|bunx|node\s+-e|python\s+-c|py\s+-c)\b", g, re.I) and not re.match(
                r"npx\s+remotion\s+(still|render|compositions)\b", g, re.I):
            return "lệnh có thể tải hoặc chạy code bất kỳ"
        if re.match(r"\s*\"?(node|python\d*|py|deno|bun|ruby|perl|java|cscript|wscript|mshta)(\.exe)?\"?\s", g + " ", re.I) \
                and _KB_THU not in [os.path.normcase(os.path.abspath(p)) for p in re.findall(r"[A-Za-z]:[\\/][^\s\"']*", g)]:
            return "chạy script (agent có thể tự viết script rồi chạy) — chỉ cho thu_canh.py"
        if ".." in re.split(r"[\s/\\\"']+", g):
            return "lệnh có đường dẫn '..'"
        for p in re.findall(r"[A-Za-z]:[\\/][^\s\"']*", g):              # đường dẫn tuyệt đối: chỉ trong chỗ được ghi
            if not any(_trong(p, x) for x in _GHI_DUOC) and os.path.normcase(os.path.abspath(p)) != _KB_THU:
                return f"lệnh đụng tới {p} (ngoài remotion/src, remotion/public, cache)"
        return ""
    if ".." in g.replace("\\", "/").split("/"):
        return "đường dẫn có '..'"
    if v["loai"] == "read_file":
        return "" if _trong(g, ROOT) else "đọc ngoài thư mục dự án"
    if not any(_trong(g, x) for x in _GHI_DUOC):
        return "ghi ngoài remotion/src, remotion/public, cache (không cho đụng code tool, dữ liệu ra/, bản nháp)"
    return ""


def _luat(v):
    return f"{v['loai']}({v['gia_tri']})"


def xin_quyen(ma, cau, v, bao=None):
    """Ghi phiếu xin quyền rồi CHỜ user bấm trên giao diện. -> 'co' | 'khong' | 'het_gio'."""
    import time
    import uuid
    bao = bao or (lambda m: log("  " + m))
    i = uuid.uuid4().hex[:10]
    f = os.path.join(_thu_xin(), f"{i}.json")
    if TU_CHO_PHEP:                                                      # bên gọi đã lọc _nguy_hiem trước khi xin
        ghi_json(f, {"id": i, "ma": ma, "cau": cau, "loai": v["loai"], "gia_tri": v["gia_tri"], "luc": time.time(),
                     "trang_thai": "co", "tu_dong": True})
        bao(f"Antigravity xin quyền {v['loai']}: {v['gia_tri'][:120]} — tự đồng ý (việc an toàn)")
        return "co"
    ghi_json(f, {"id": i, "ma": ma, "cau": cau, "loai": v["loai"], "gia_tri": v["gia_tri"], "luc": time.time(),
                 "trang_thai": "cho"})
    bao(f"Antigravity xin quyền {v['loai']}: {v['gia_tri'][:120]} — chờ bạn bấm trên giao diện…")
    het = time.time() + CHO_DUYET
    while time.time() < het:
        time.sleep(2)
        p = doc_json(f, {}) or {}
        if p.get("trang_thai") in ("co", "khong"):
            if p["trang_thai"] == "co" and p.get("luon"):
                ds = luat_luon()
                if _luat(v) not in ds:
                    ghi_json(_f_luon(), ds + [_luat(v)])
            return p["trang_thai"]
    ghi_json(f, (doc_json(f, {}) or {}) | {"trang_thai": "het_gio"})
    return "het_gio"


