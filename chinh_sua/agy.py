def hoi(prompt, thu_muc=(), timeout=420, cho_phep=None, cwd=None):
    """Một lượt agy -p -> chữ trả lời ('' nếu hỏng). cho_phep=None: sandbox, chỉ đọc thư mục cấp; cho_phep=[luật]: không
    sandbox, chỉ đúng các luật này (command(<lệnh trọn chuỗi>), write_file(<thư mục>))."""
    return hoi_tho(prompt, thu_muc, timeout, cho_phep, cwd)["response"]


def hoi_tho(prompt, thu_muc=(), timeout=420, cho_phep=None, cwd=None, cuoc=None, mo_hinh=None):
    """Như hoi() nhưng trả {response, cuoc (mã cuộc trò chuyện), bi_chan (có việc bị từ chối)}. cuoc: chạy TIẾP cuộc cũ."""
    rong = {"response": "", "cuoc": cuoc, "bi_chan": False}
    if not co():
        return rong
    thu_muc = list(thu_muc)
    if len(prompt) > 28000:                                              # dòng lệnh Windows giới hạn ~32k ký tự: lời nhắn
        import hashlib                                                   # dài (kèm code cảnh) ghi ra tệp nhiệm vụ cho agent đọc
        from common import CACHE_CHUNG
        thu = os.path.join(CACHE_CHUNG, "nhan_y", "agy_nhiem_vu")
        os.makedirs(thu, exist_ok=True)
        f = os.path.join(thu, hashlib.md5(prompt.encode("utf-8")).hexdigest()[:12] + ".md")
        with open(f, "w", encoding="utf-8") as g:
            g.write(prompt)
        thu_muc.append(thu)
        prompt = (f"Read the task file {f} completely and do exactly what it asks. Your final answer must be only the "
                  "output format that the task file requests.")
    lenh = [AGY, "-p", prompt, "--model", mo_hinh or MO_HINH, "--output-format", "json", "--print-timeout", f"{timeout}s"]
    lenh += ["--settings", json.dumps({"permissions": {"allow": list(cho_phep)}})] if cho_phep is not None else ["--sandbox"]
    for d in thu_muc:
        lenh += ["--add-dir", d]
    if cuoc:
        lenh += ["--conversation", cuoc]
    try:
        r = subprocess.run(lenh, capture_output=True, timeout=timeout + 60, cwd=cwd,
                           creationflags=0x08000000 if os.name == "nt" else 0)
    except subprocess.TimeoutExpired:
        log("    (Antigravity quá giờ)")
        return rong
    try:
        d = json.loads((r.stdout or b"").decode("utf-8", "ignore").strip().splitlines()[-1])
    except (ValueError, IndexError):
        log(f"    (Antigravity không trả JSON: {(r.stderr or b'').decode('utf-8', 'ignore')[-200:]})")
        return rong
    if d.get("status") != "SUCCESS":
        log(f"    (Antigravity: {d.get('status')} {str(d.get('error') or '')[:160]})")
    if d.get("denied_actions"):
        log(f"    (Antigravity bị từ chối: {[x.get('display_name') for x in d['denied_actions']]})")
    return {"response": str(d.get("response") or ""), "cuoc": d.get("conversation_id") or cuoc,
            "bi_chan": bool(d.get("denied_actions"))}


