def chay_co_xin(prompt, thu_muc, timeout, cho_phep, cwd, ma, cau, bao=None, mo_hinh=None):
    """hoi_tho + vòng xin quyền: bị chặn -> (nguy hiểm: tự từ chối) | hỏi user -> chạy tiếp cuộc cũ. -> chữ trả lời."""
