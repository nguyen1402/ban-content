def _ds_anh(du_an):
    """[{file, cau, text, ve, nguon}] — ảnh AI của bước ✨ (ke_hoach.json) + ảnh của các cảnh Remotion AI. Không Veo."""
    out = thu_muc_du_an(du_an)[1]
    ra = []
    for y in (doc_json(os.path.join(out, "ke_hoach.json"), {}) or {}).get("anh_ai") or []:
        ve = y.get("ve") or []
        for j, f in enumerate(y.get("ds_anh") or []):
            if os.path.isfile(f):
                ra.append({"file": f, "cau": y.get("cau"), "text": y.get("text") or "", "ve": ve[j] if j < len(ve) else "",
                           "nguon": "✨ ảnh AI"})
    pub = os.path.join(ROOT, "remotion", "public")
    for v in (doc_json(os.path.join(out, "nhan_y_ai.json"), {}) or {}).values():
        for a in v.get("anh") or []:
            f = os.path.join(pub, a.get("file") or "")
            if os.path.isfile(f):
                ve = next((x.get("ve") for x in (v.get("thiet_ke") or {}).get("anh") or [] if x.get("ten") == a.get("ten")), "")
                ra.append({"file": f, "cau": v.get("cau"), "text": v.get("text") or "", "ve": ve or "", "nguon": "🎞 Remotion"})
    return ra


def cham_anh(du_an, bao=None):
    """Antigravity chấm mọi ảnh AI của dự án -> ra/<dự án>/cham_anh.json {file: {...}}."""
    bao = bao or (lambda m: log("  " + m))
    ds = _ds_anh(du_an)
    p = os.path.join(thu_muc_du_an(du_an)[1], "cham_anh.json")
    kq = doc_json(p, {}) or {}
    can = [a for a in ds if str(os.path.getmtime(a["file"])) != str((kq.get(a["file"]) or {}).get("mtime"))]
    bao(f"Antigravity chấm {len(can)}/{len(ds)} ảnh AI (đã chấm, chưa đổi thì bỏ qua)…")
    for i in range(0, len(can), MOT_LUOT_ANH):
        lo = can[i:i + MOT_LUOT_ANH]
        mo = "\n".join(f"- {a['file']}\n  sentence: «{a['text'][:300]}»\n  prompt: «{a['ve'][:400]}»" for a in lo)
        thu = sorted({os.path.dirname(a["file"]) for a in lo})
        r = rut_json(hoi(_HOI_ANH.format(ds=mo), thu)) or {}
        # khớp theo TÊN tệp (agent hay trả đường dẫn khác dạng: / thay \, tương đối…)
        theo = {os.path.basename(str(x.get("file") or "").replace("\\", "/")).lower(): x for x in r.get("anh") or []
                if isinstance(x, dict)}
        for a in lo:
            x = theo.get(os.path.basename(a["file"]).lower())
            if not x:
                continue
            kq[a["file"]] = {"diem": x.get("diem"), "dung_noi_dung": x.get("dung_noi_dung"), "loi": x.get("loi") or [],
                             "nhan_xet": x.get("nhan_xet") or "", "cau": a["cau"], "nguon": a["nguon"],
                             "mtime": str(os.path.getmtime(a["file"]))}
        ghi_json(p, kq)
        bao(f"Antigravity: đã chấm {min(i + MOT_LUOT_ANH, len(can))}/{len(can)} ảnh")
    return kq


