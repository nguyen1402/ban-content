def duyet_canh(cau, y_chinh, mo_ta, khung, thu_muc):
    """khung = [(giây, png)] -> (dat, diem | None, [lỗi])"""
    k = ", ".join(f"{p} (t={t:.1f}s)" for t, p in khung)
    r = rut_json(hoi(_HOI_CANH.format(cau=cau, y_chinh=y_chinh or "", mo_ta=mo_ta or "", khung=k), thu_muc, timeout=300)) or {}
    if r.get("diem") is None:
        return False, None, []
    return bool(r.get("dat")) and int(r.get("diem") or 0) >= DAT, r.get("diem"), r.get("loi") or []


